import mongoose from 'mongoose';

const MONGODB_URI = process.env.MONGODB_URI || 'mongodb://localhost:27017/money_manager';

// Schemas
const transactionSchema = new mongoose.Schema({
  userId: { type: mongoose.Schema.Types.ObjectId, ref: 'User', required: true },
  date: { type: String, required: true },
  account: { type: String, required: true },
  category: { type: String, required: true },
  subcategory: { type: String, default: '' },
  note: { type: String, default: '' },
  amount: { type: Number, required: true },
  inr: { type: Number },
  currency: { type: String, default: 'INR' },
  type: { type: String, required: true },
  description: { type: String, default: '' },
  time: { type: String, default: '' },
  created_at: { type: Date, default: Date.now },
});

const deletedTransactionSchema = new mongoose.Schema({
  userId: { type: mongoose.Schema.Types.ObjectId, ref: 'User', required: true },
  transactionId: mongoose.Schema.Types.Mixed,
  date: { type: String, required: true },
  account: { type: String, required: true },
  category: { type: String, required: true },
  subcategory: { type: String, default: '' },
  note: { type: String, default: '' },
  amount: { type: Number, required: true },
  inr: { type: Number },
  currency: { type: String, default: 'INR' },
  type: { type: String, required: true },
  description: { type: String, default: '' },
  time: { type: String, default: '' },
  deleted_at: { type: Date, default: Date.now },
  original_created_at: { type: Date },
});

const userSchema = new mongoose.Schema({
  username: { type: String, required: true, unique: true, lowercase: true, trim: true },
  email: { type: String, required: true, unique: true, lowercase: true, trim: true },
  password: { type: String, required: true },
  created_at: { type: Date, default: Date.now },
});

const Transaction = mongoose.models.Transaction || mongoose.model('Transaction', transactionSchema);
const DeletedTransaction = mongoose.models.DeletedTransaction || mongoose.model('DeletedTransaction', deletedTransactionSchema);
const User = mongoose.models.User || mongoose.model('User', userSchema);

const ACCOUNTS = ['Cash', '🏦 Kotak Bank', '🏦 Union Bank'];
const CATEGORIES = [
  '🍜 Food',
  '🚖 Transport',
  '🧘🏼 Health',
  '🪑 Household',
  '💼 Office Work',
  '🎉 Entertainment',
  '📚 Education',
  '🛒 Shopping',
  '💊 Medicine',
  '🏠 Rent',
  '⚡ Utilities',
];
const TYPES = ['Expense', 'Expense', 'Expense', 'Income', 'Income']; // Weighted towards expenses

function getRandomInt(min, max) {
  return Math.floor(Math.random() * (max - min + 1)) + min;
}

function getRandomDate() {
  const start = new Date(new Date().getFullYear(), new Date().getMonth() - 2, 1);
  const end = new Date();
  const date = new Date(start.getTime() + Math.random() * (end.getTime() - start.getTime()));
  return date.toISOString().split('T')[0];
}

function generateRandomTransaction(userId) {
  const type = TYPES[getRandomInt(0, TYPES.length - 1)];
  const category = type === 'Income' ? '💼 Salary' : CATEGORIES[getRandomInt(0, CATEGORIES.length - 1)];
  let amount = 0;
  
  if (type === 'Income') {
    amount = getRandomInt(10000, 50000);
  } else {
    amount = getRandomInt(100, 5000);
  }

  return {
    userId,
    date: getRandomDate(),
    time: `${String(getRandomInt(8, 22)).padStart(2, '0')}:${String(getRandomInt(0, 59)).padStart(2, '0')}`,
    account: ACCOUNTS[getRandomInt(0, ACCOUNTS.length - 1)],
    category,
    note: `Random ${category} transaction`,
    amount,
    inr: amount,
    currency: 'INR',
    type,
    description: 'Generated by reset script'
  };
}

async function run() {
  try {
    await mongoose.connect(MONGODB_URI);
    console.log('Connected to MongoDB');

    const demoUser = await User.findOne({ username: 'demo' });
    if (!demoUser) {
      console.log('Demo user not found!');
      process.exit(1);
    }

    console.log(`Found demo user: ${demoUser._id}`);

    // Delete existing transactions
    const txDeleteResult = await Transaction.deleteMany({ userId: demoUser._id });
    console.log(`Deleted ${txDeleteResult.deletedCount} transactions`);

    const delTxDeleteResult = await DeletedTransaction.deleteMany({ userId: demoUser._id });
    console.log(`Deleted ${delTxDeleteResult.deletedCount} deleted transactions`);

    // Generate new random transactions (e.g., 50 transactions)
    const transactionsToInsert = [];
    for (let i = 0; i < 50; i++) {
      transactionsToInsert.push(generateRandomTransaction(demoUser._id));
    }

    await Transaction.insertMany(transactionsToInsert);
    console.log(`Inserted ${transactionsToInsert.length} random transactions for demo account`);

  } catch (error) {
    console.error('Error:', error);
  } finally {
    await mongoose.disconnect();
    console.log('Disconnected from MongoDB');
    process.exit(0);
  }
}

run();
